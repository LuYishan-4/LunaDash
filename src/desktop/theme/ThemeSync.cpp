QJsonObject synchronizeApplicationTheme() {
  static QByteArray previous;
  static QJsonObject result;
  const auto preferences = desktopPreferences();
  const auto palette = appearancePalette(preferences);
  const bool enabled = preferences.value("syncApplicationThemes").toBool();
  const bool fcitx = preferences.value("syncFcitxTheme").toBool();
  const auto fingerprint =
      QJsonDocument(palette).toJson(QJsonDocument::Compact) +
      (enabled ? "1" : "0") + (fcitx ? "1" : "0");
  if (fingerprint == previous)
    return result;
  previous = fingerprint;
  const auto config =
      QStandardPaths::writableLocation(QStandardPaths::GenericConfigLocation);
  const auto directory = config + "/lunadash/theme";
  result = {{"enabled", enabled}, {"directory", directory}, {"error", ""}};
  QString fcitxError;
  if (fcitx && !synchronizeFcitxTheme(palette, &fcitxError))
    result["error"] = fcitxError;

  // The desktop light/dark preference is a system preference, not an
  // application-theme override. Publish it even when optional GTK/Kitty theme
  // file synchronization is disabled so native GTK applications and other
  // consumers of org.gnome.desktop.interface follow LunaDash as well.
  setColorScheme(palette.value("dark").toBool());

  if (!enabled)
    return result;
  const auto color = [&palette](const QString &key) {
    return palette.value(key).toString();
  };
  QString error;
  const auto gtk =
      QString("@define-color theme_bg_color %1;\n@define-color theme_fg_color "
              "%2;\n@define-color theme_base_color %3;\n@define-color "
              "theme_selected_bg_color %4;\n@define-color "
              "theme_selected_fg_color %5;\n@define-color accent_color "
              "%4;\n@define-color accent_bg_color %4;\n@define-color "
              "accent_fg_color %5;\n@define-color window_bg_color "
              "%1;\n@define-color window_fg_color %2;\n@define-color "
              "view_bg_color %3;\n@define-color view_fg_color %2;\n")
          .arg(color("background"), color("text"), color("surface"),
               color("accent"), color("accentInk"));
  const auto kitty =
      QString("# Generated by LunaDash. Include from kitty.conf.\nbackground "
              "%1\nforeground %2\nselection_background "
              "%3\nselection_foreground %4\ncursor %3\nurl_color %3\n")
          .arg(color("background"), color("text"), color("accent"),
               color("accentInk"));
  if (!write(directory + "/gtk.css", gtk.toUtf8(), &error) ||
      !write(directory + "/kitty.conf", kitty.toUtf8(), &error)) {
    result["error"] = error;
    return result;
  }
  const auto import = "@import url(\"" +
                      QUrl::fromLocalFile(directory + "/gtk.css").toEncoded() +
                      "\");";
  for (const auto &version : {"gtk-3.0", "gtk-4.0"}) {
    const auto base = config + "/" + version;
    if (!includeOnce(base + "/gtk.css", import, &error))
      break;
    QSettings settings(base + "/settings.ini", QSettings::IniFormat);
    settings.setValue("Settings/gtk-application-prefer-dark-theme",
                      palette.value("dark").toBool() ? 1 : 0);
    settings.sync();
    if (settings.status() != QSettings::NoError) {
      error = "Could not save GTK theme preference.";
      break;
    }
  }
  const auto kittyConfig = config + "/kitty/kitty.conf";
  if (error.isEmpty() && QFileInfo::exists(kittyConfig))
    includeOnce(kittyConfig, QByteArray("include ../lunadash/theme/kitty.conf"),
                &error);
  result["error"] = error.isEmpty() ? fcitxError : error;
  return result;
}
