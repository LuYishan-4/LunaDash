bool write(const QString &path, const QByteArray &text, QString *error) {
  if (!QDir().mkpath(QFileInfo(path).absolutePath())) {
    *error = "Could not create theme directory.";
    return false;
  }
  QSaveFile file(path);
  if (!file.open(QIODevice::WriteOnly) || file.write(text) != text.size() ||
      !file.commit()) {
    *error = file.errorString();
    return false;
  }
  return true;
}
bool includeOnce(const QString &path, const QByteArray &line, QString *error) {
  QFile file(path);
  QByteArray text;
  if (file.exists()) {
    if (!file.open(QIODevice::ReadOnly) || file.size() > 1024 * 1024) {
      *error =
          "Theme integration requires a readable configuration below 1 MiB: " +
          path;
      return false;
    }
    text = file.readAll();
    if (text.contains(line))
      return true;
    // Keep the first pre-integration configuration for manual restoration.
    if (!QFileInfo::exists(path + ".lunadash-backup") &&
        !file.copy(path + ".lunadash-backup")) {
      *error = "Could not back up configuration: " + path;
      return false;
    }
  }
  return write(path,
               line.startsWith("@import") ? line + "\n" + text
                                          : text + "\n" + line + "\n",
               error);
}
void setColorScheme(bool dark) {
  const auto program = QStandardPaths::findExecutable("gsettings");
  if (program.isEmpty())
    return;
  auto *process = new QProcess(QCoreApplication::instance());
  auto *timer = new QTimer(process);
  timer->setSingleShot(true);
  QObject::connect(timer, &QTimer::timeout, process,
                   [process] { process->kill(); });
  QObject::connect(process, &QProcess::finished, process,
                   &QObject::deleteLater);
  QObject::connect(process, &QProcess::errorOccurred, process,
                   [process](QProcess::ProcessError error) {
                     if (error == QProcess::FailedToStart)
                       process->deleteLater();
                   });
  process->setStandardOutputFile(QProcess::nullDevice());
  process->setStandardErrorFile(QProcess::nullDevice());
  process->start(program, {"set", "org.gnome.desktop.interface", "color-scheme",
                           dark ? "prefer-dark" : "prefer-light"});
  timer->start(3000);
}
